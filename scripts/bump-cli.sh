#!/bin/bash

# Pin the trunk CLI version that trunk-action installs.
#
# Usage: scripts/bump-cli.sh <version> [channel]
#
# Reads https://trunk.io/releases/trunk-cli/<channel>/<version>/manifest.json and rewrites
# setup/cli-pins.sh with the version, the channel (default: prod) and the sha256 of each platform.
# The release must have a build for each platform in PLATFORMS. Requires curl and jq.

set -euo pipefail

PLATFORMS=(linux-x64 linux-arm64 darwin-arm64 darwin-x64)

if [[ $# -lt 1 || $# -gt 2 ]]; then
  echo "Usage: $0 <version> [channel]" >&2
  exit 2
fi
version="$1"
channel="${2:-prod}"

if [[ ! ${version} =~ ^[0-9]+\.[0-9]+\.[0-9]+([-+][0-9A-Za-z.-]+)?$ ]]; then
  echo "Invalid version: ${version}" >&2
  exit 2
fi
if [[ ! ${channel} =~ ^[a-z0-9-]+$ ]]; then
  echo "Invalid channel: ${channel}" >&2
  exit 2
fi

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
pins_file="${repo_root}/setup/cli-pins.sh"
trap 'rm -f "${pins_file}.tmp"' EXIT

manifest="$(curl -fsSL "https://trunk.io/releases/trunk-cli/${channel}/${version}/manifest.json")"
manifest_version="$(jq -r '.version' <<<"${manifest}")"
if [[ ${manifest_version} != "${version}" ]]; then
  echo "Manifest version '${manifest_version}' does not match '${version}'" >&2
  exit 1
fi

{
  echo "# shellcheck shell=bash"
  echo "# Generated by scripts/bump-cli.sh. Do not edit by hand."
  echo "# The trunk CLI version that trunk-action installs, and the sha256 of each platform's tarball."
  echo
  echo "export TRUNK_CLI_PIN_VERSION=\"${version}\""
  echo "export TRUNK_CLI_PIN_CHANNEL=\"${channel}\""
  for platform in "${PLATFORMS[@]}"; do
    sha="$(jq -r --arg p "${platform}" '.platforms[$p].sha256 // empty' <<<"${manifest}")"
    if [[ ! ${sha} =~ ^[0-9a-f]{64}$ ]]; then
      echo "trunk CLI ${version} (${channel}) has no ${platform} build" >&2
      exit 1
    fi
    echo "export TRUNK_CLI_PIN_SHA256_${platform//-/_}=\"${sha}\""
  done
} >"${pins_file}.tmp"
mv "${pins_file}.tmp" "${pins_file}"

echo "Pinned trunk CLI ${version} (${channel}) in setup/cli-pins.sh"
